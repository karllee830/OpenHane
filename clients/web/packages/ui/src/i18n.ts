export type Locale = 'zh-CN' | 'en';
/** 导出给测试：检查各语言的占位符是否一致 */
export const dicts: Record<Locale, Record<MessageKey, string>> = { 'zh-CN': zh, en };

export function pickLocale(langs: readonly string[] = typeof navigator !== 'undefined' ? navigator.languages : []): Locale {
  for (const l of langs) {
    if (l.toLowerCase().startsWith('zh')) return 'zh-CN';
    if (l.toLowerCase().startsWith('en')) return 'en';
  }
  return 'zh-CN';
}

export type Translate = (key: MessageKey, vars?: Record<string, string | number>) => string;

export function translator(locale: Locale): Translate {
  const d = dicts[locale];
  return (key, vars) => {
    let s = d[key] ?? zh[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
    return s;
  };
}

export const I18nContext = createContext<Translate>(translator('zh-CN'));
export const useT = () => useContext(I18nContext);
